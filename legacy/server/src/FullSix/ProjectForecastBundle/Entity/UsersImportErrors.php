<?php

namespace FullSix\ProjectForecastBundle\Entity;

/**
 * UsersImportErrors
 */
class UsersImportErrors
{
    /**
     * @var string
     */
    protected $username;

    /**
     * @var string
     */
    protected $email;

    /**
     * @var string
     */
    protected $firstname;

    /**
     * @var string
     */
    protected $lastname;

    /**
     * @var string
     */
    protected $initials;

    /**
     * @var string
     */
    protected $status;


